// ── Types ─────────────────────────────────────────────────────────────────────

export type StagingModule = 'denial' | 'underpayment' | 'audit' | 'unknown'

export type StagingSignalType =
  | '835'
  | 'pdf-denial'
  | 'pdf-adr'
  | 'pdf-audit-notice'
  | 'spreadsheet'
  | 'manual'
  | 'portal'

export type StagingStatus =
  | 'processing'
  | 'auto_processed'
  | 'needs_review'
  | 'resolved'
  | 'dismissed'
  | 'expired'

export type NeedsReviewReason =
  | 'missing_fields'
  | 'low_confidence'
  | 'low_confidence_patient'
  | 'no_patient_match'
  | 'no_claim_match'
  | 'ambiguous_classification'
  | 'possible_duplicate'
  | 'existing_instance_found'
  | 'no_clinical_data'
  | 'letter_generation_failure'
  | 'extraction_failure'

export interface StagingRecord {
  id: string
  module: StagingModule
  signalType: StagingSignalType
  status: StagingStatus
  reviewReasons: NeedsReviewReason[]
  patientName: string | null
  patientMrn: string | null
  payer: string | null
  amount: number | null
  classifiedAs: string | null
  classificationConfidence: 'high' | 'medium' | 'low' | null
  receivedAt: string
  sourceFile: string | null
  connectionId: string | null
  autoProcessedAt: string | null
  autoProcessedInstanceId: string | null
  resolvedAt: string | null
  resolvedBy: string | null
  dismissedAt: string | null
  dismissReason: string | null
  extraction: Record<string, unknown>
}

// ── Helpers ───────────────────────────────────────────────────────────────────

// Base date: 2026-04-03 (prototype reference date) — signals arrive same day
function t(offsetMinutes: number): string {
  const base = new Date('2026-04-03T06:00:00')
  base.setMinutes(base.getMinutes() + offsetMinutes)
  return base.toISOString()
}

